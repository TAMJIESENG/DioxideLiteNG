# -*- coding: utf-8 -*-
"""Build intro-site/assets/js/feature-data.js from the real source tree.

For every module class under com/dioxideliteng/module/<category>/ it extracts:
  display name (from super("...")), line count, setting labels/types/mode options.
Human-facing 中文名 + 一句话说明 come from tools/features.py.
Modules without a curated entry fall back to an explicit 待补充 placeholder.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.abspath(os.path.join(HERE, ".."))
ROOT = os.path.abspath(os.path.join(SITE, ".."))
sys.path.insert(0, HERE)

from features import FEATURES  # noqa: E402

CATEGORIES = [
    ("COMBAT", "module/combat", "战斗"),
    ("MOVEMENT", "module/movement", "移动"),
    ("PLAYER", "module/player", "玩家"),
    ("MISC", "module/misc", "杂项"),
    ("VISUAL", "module/visual", "视觉"),
]

SETTING_RE = re.compile(
    r'new\s+(BooleanSetting|NumberSetting|ModeSetting|MultiSelectSetting|TextSetting|ChoiceSetting)\(\s*"([^"]+)"'
    r'(?:\s*,\s*[^,]+,\s*"([^"]*)"\s*,\s*new\s+String\[\]\s*\{([^}]*)\})?'
)
SUPER_RE = re.compile(r'super\(\s*"([^"]+)"')


def loc_of(path):
    with open(path, encoding="utf-8", errors="replace") as fh:
        return fh.read().count("\n")


def settings_of(src):
    out = []
    for m in SETTING_RE.finditer(src):
        kind, label, default, options = m.group(1), m.group(2), m.group(3), m.group(4)
        item = {"label": label, "type": kind.replace("Setting", "")}
        if options:
            opts = [o.strip().strip('"') for o in options.split(",") if o.strip()]
            item["options"] = opts[:6]
            if default:
                item["default"] = default
        if item not in out:
            out.append(item)
    return out[:8]


payload = {"categories": {}, "counts": {}, "total": 0, "missing": []}

for key, rel, cn in CATEGORIES:
    folder = os.path.join(ROOT, "com", "dioxideliteng", rel.replace("/", os.sep))
    mods = []
    for fname in sorted(os.listdir(folder)):
        if not fname.endswith(".java"):
            continue
        cls = fname[:-5]
        path = os.path.join(folder, fname)
        src = open(path, encoding="utf-8", errors="replace").read()
        if not re.search(r"class\s+" + re.escape(cls) + r"\b", src):
            continue
        sm = SUPER_RE.search(src)
        display = sm.group(1) if sm else ""
        curated = FEATURES.get(cls)
        if curated is None:
            payload["missing"].append(cls)
            name_cn, desc = "（待补充：模块名）", "（待补充：功能说明）"
        else:
            name_cn, desc = curated
            if display and display.lower() == cls.lower():
                display = ""
        mods.append({
            "cls": cls,
            "name": display or cls,
            "cn": name_cn,
            "desc": desc,
            "loc": loc_of(path),
            "file": "com/dioxideliteng/%s/%s" % (rel, fname),
            "settings": settings_of(src),
        })
    payload["categories"][key] = {"label": cn, "dir": "com/dioxideliteng/" + rel, "modules": mods}
    payload["counts"][key] = len(mods)
    payload["total"] += len(mods)

# 目录规模（与页面上一致的口径）
per_dir = {}
for base in ("com", "mixins"):
    for dirpath, _dirs, files in os.walk(os.path.join(ROOT, base)):
        for f in files:
            if f.endswith(".java"):
                rel = os.path.relpath(dirpath, ROOT).replace("\\", "/")
                per_dir[rel] = per_dir.get(rel, 0) + loc_of(os.path.join(dirpath, f))
payload["dirs"] = sorted(per_dir.items(), key=lambda kv: -kv[1])[:12]
payload["javaFiles"] = sum(1 for base in ("com", "mixins")
                           for _d, _s, fs in os.walk(os.path.join(ROOT, base))
                           for f in fs if f.endswith(".java"))
payload["javaLoc"] = sum(per_dir.values())

out_dir = os.path.join(SITE, "assets", "js")
os.makedirs(out_dir, exist_ok=True)
with open(os.path.join(out_dir, "feature-data.js"), "w", encoding="utf-8") as fh:
    fh.write("/* generated by tools/build_feature_data.py — 数据来自项目源码 */\n")
    fh.write("window.DLX_FEATURES = ")
    fh.write(json.dumps(payload, ensure_ascii=False, indent=1))
    fh.write(";\n")

print("counts:", payload["counts"], "total:", payload["total"])
print("javaFiles:", payload["javaFiles"], "javaLoc:", payload["javaLoc"])
print("no curated description (%d):" % len(payload["missing"]), ", ".join(payload["missing"]))
